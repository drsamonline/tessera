"""Generate CONFORMANCE.md from the suite, not from memory.

Every number in the output comes from `conformance.run_conformance` against a
real connector object. If a check fails the document says so; there is no branch
that writes "pass" for a connector that did not run.
"""
from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from tessera import conformance                       # noqa: E402
from tessera.connectors import NativeConnector        # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent


WHAT_EACH_CHECK_ANSWERS = {
    "capabilities_present": "Does it declare capabilities at all, rather than being assumed?",
    "capabilities_declare_objects": "Does it list the objects it serves?",
    "capabilities_use_canonical_objects": "Are those objects the canonical ones, not vendor names?",
    "schema_present": "Does it describe its fields?",
    "schema_maps_only_canonical_fields": "Does the description use canonical field names, not vendor ones?",
    "schema_covers_declared_objects": "Does every object it claims to serve have a schema?",
    "write_accepts_valid_payload": "Does a valid canonical record get accepted?",
    "read_returns_valid_records": "Do the records that come back validate against the canonical schema?",
    "read_pagination_terminates": "Does paging stop, rather than loop on a cursor that never advances?",
    "write_is_idempotent": "Does the same idempotency key twice create one record or two?",
    "write_rejects_invalid_payload": "Is an invalid record refused, rather than stored and repaired later?",
    "round_trip": "Does what you wrote come back, field for field?",
    "health_is_valid": "Is there a health signal, and does it carry a reason?",
    "rate_limit_is_positive": "Is a rate limit reported, and is it a real number?",
    "cost_estimate_non_negative": "Can routing price an operation before doing it, without a negative?",
    "errors_are_from_the_taxonomy": "Do failures map onto the shared error classes?",
}


def build_all():
    """Every connector this repository ships, built the way the tests build them."""
    from tests.test_providers import hubspot, salesforce, zendesk
    return [
        ("HubSpot", "CRM v3 · sales", hubspot()[0]),
        ("Salesforce", "REST v60 · sales", salesforce()[0]),
        ("Zendesk", "Support API v2 · support", zendesk()[0]),
        ("Native", "in-process store · native", NativeConnector(page_size=2)),
    ]


def main() -> int:
    rows, failures = [], 0
    for label, detail, node in build_all():
        report = conformance.run_conformance(node)
        passed = sum(1 for c in report.checks if c.ok)
        total = len(report.checks)
        failures += 0 if report.ok else 1
        rows.append((label, detail, passed, total, report))

    names = [c.name for c in rows[0][4].checks]
    lines = [
        "# Conformance",
        "",
        "**Generated by `scripts/conformance_report.py`.** Every figure below comes from running",
        "`conformance.run_conformance` against a real connector object in this repository. Nothing here is",
        "asserted by hand, and the script fails rather than writing a pass for a connector that did not run.",
        "",
        "## The four connectors",
        "",
        "| Connector | Dialect | Checks | Result |",
        "|---|---|---|---|",
    ]
    for label, detail, passed, total, report in rows:
        verdict = "pass" if report.ok else f"**{len(report.failures)} failed**"
        lines.append(f"| {label} | {detail} | {passed}/{total} | {verdict} |")

    lines += [
        "",
        "## What each check proves",
        "",
        "| Check | The question it answers |",
        "|---|---|",
    ]
    for name in names:
        question = WHAT_EACH_CHECK_ANSWERS.get(name)
        if question is None:
            question = "*(no description recorded — add one to WHAT_EACH_CHECK_ANSWERS)*"
        lines.append(f"| `{name}` | {question} |")
    lines += [
        "",
        "## The per-check results",
        "",
        "| Check | " + " | ".join(label for label, *_ in rows) + " |",
        "|---|" + "---|" * len(rows),
    ]
    for name in names:
        cells = []
        for *_, report in rows:
            check = next((c for c in report.checks if c.name == name), None)
            cells.append("pass" if check and check.ok else "**fail**")
        lines.append(f"| `{name}` | " + " | ".join(cells) + " |")

    lines += [
        "",
        "## The caveat this document cannot remove",
        "",
        "Every result above is produced against a **recorded transport** that speaks each provider's documented",
        "shapes, or against the in-process store. No connector in this repository has made a request to a live",
        "tenant. The suite proves the contract is implemented; it does not prove a vendor's production API agrees",
        "with its own documentation on a Tuesday.",
        "",
        "A live sweep is the next step and needs one thing this repository does not have: a sandbox token.",
        "",
    ]
    (ROOT / "CONFORMANCE.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"CONFORMANCE.md written — {len(rows)} connectors, {len(names)} checks, {failures} failing")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
